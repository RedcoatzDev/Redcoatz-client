"""Turn a map's DISPLAYED name into its key.

The lobby browser advertises each open game by the map name as the HOST's game
renders it -- localised into the host's language. A player running the Chinese
build advertises "1812 - 博罗季诺", and one running English advertises
"1812 - Borodino". Both are the same map, `ntw3_hb_1812_borodino`, and nothing
in the record says so: the name sits in a general string pool with no key and
no id beside it, so there is nothing else to read.

So this resolves what it can and is honest about the rest. A name it does not
recognise returns None, which the caller must treat as "map unknown" rather
than passing a foreign string on as if it were an identity -- that is what put
Chinese text in the panel and 404ed the map preview.

# Why a table and not a translation

The table is generated from web/public/maps/index.json, which carries the
English `shown` and `name` for every map the site knows. It therefore resolves
hosts running English and nobody else. Covering other languages needs their
localisation tables, which are not on this machine; until then a foreign host
means an unknown map, which is the truthful answer and a better one than a
confident wrong guess.
"""

