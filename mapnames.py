#: What a decoder puts where a letter could not be read.
REPLACEMENT = "\ufffd"


def to_key(shown):
    """The map key for a displayed name, or None when it is not recognised.

    A key passes straight through: the thumbnail signal hands back keys while
    the browser record hands back display names, and callers should not have
    to know which they hold.
    """
    if not shown:
        return None
    s = shown.strip()
    if s in NAMES:
        return NAMES[s]
    low = s.lower()
    if low.startswith(("ntw3_", "nap_", "rti_")):
        return low
    for name, key in NAMES.items():
        if name.lower() == low:
            return key
    # A letter the sender's game could not encode arrives as U+FFFD, e.g.
    # "1805 - Sch\ufffdngrabern" from a host outside a Latin locale. Each one
    # matches any single letter, and only a unique match is believed.
    if REPLACEMENT in s:
        pat = re.compile("".join("." if c == REPLACEMENT else re.escape(c)
                                 for c in low) + r"\Z")
        hits = {key for name, key in NAMES.items() if pat.match(name.lower())}
        if len(hits) == 1:
            return hits.pop()
    return None
